// Token Radar model v2 (radar-2): one sealed snapshot in, one ranked board out.
//
// The board ranks pre-token protocols by an implied value that is derived from the
// snapshot's own figures, never from a hand-kept list of names:
//
//   sector   = the category's own market multiple: the median mcap / TVL of the
//              live-token protocols in the same category (at least 3 comps), or
//              the whole live market's median when a category has too few comps,
//              clamped to [0.05, 0.80]. A DEX is priced like live DEXs, a lender
//              like live lenders, because the market already told us what each
//              kind of protocol is worth per dollar of TVL.
//   growth   = clamp(change_7d, -60, 120) per cent
//   growthM  = 1 + (growth / 100) * 0.5
//   maturity = 0.6 + min(age_days, 1095) / 1095 * 0.4   (age unknown: 365 days)
//   breadth  = 1 + min(chains - 1, 9) * 0.01            (wider distribution)
//   implied  = max(1, round(tvl_usd * sector * growthM * maturity * breadth))
//
// Coverage: every watchlist slug is ranked, plus every other pre-token protocol
// below the floor that could plausibly launch a token of its own — the same
// exclusions the house used for the watchlist (no CEX, no bridge / liquid
// staking / restaking category, no versioned pool, no wrapped or staked product,
// no exchange-branded name). Protocols whose token already trades are kept
// apart and shown with their market cap, never mixed into the ranking.

export interface SnapshotProtocol {
  slug: string;
  name: string;
  category: string | null;
  chains: string[];
  tvl_usd: number;
  change_7d: number | null;
  mcap_usd: number | null;
  listed_at: string | null;
  gecko_id: string | null;
  symbol: string | null;
}

export interface Snapshot {
  as_of: string;
  source: string;
  floor_usd: number;
  protocols: SnapshotProtocol[];
  watchlist: string[];
}

export interface ModelConstants {
  growth_weight: number;
  growth_floor: number;
  growth_cap: number;
  maturity_floor: number;
  maturity_range: number;
  maturity_days: number;
  unknown_age_days: number;
  sector_min: number;
  sector_max: number;
  sector_min_comps: number;
  breadth_per_chain: number;
  breadth_max_chains: number;
}

export const MODEL: ModelConstants = {
  growth_weight: 0.5,
  growth_floor: -60,
  growth_cap: 120,
  maturity_floor: 0.6,
  maturity_range: 0.4,
  maturity_days: 1095,
  unknown_age_days: 365,
  sector_min: 0.05,
  sector_max: 0.8,
  sector_min_comps: 3,
  breadth_per_chain: 0.01,
  breadth_max_chains: 9,
};

